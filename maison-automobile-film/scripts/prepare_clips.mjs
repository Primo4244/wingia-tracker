// Turn raw phone footage into film-ready clips.
//
//   1. Drop the raw files in  incoming/  named after their slot:
//        k4  a3  rav4  gle  cayenne   (hero shot of each car, horizontal)
//        night                        (headlight shot, horizontal)
//        macro                        (close-up, vertical)
//        pass                         (optional drive-by, vertical)
//      with any of .mp4 .mov .m4v .mkv  (e.g. incoming/rav4.mov)
//   2. node scripts/prepare_clips.mjs
//   3. Clips land in public/cars/clips/<slot>.mp4 and src/lib/clips.generated.ts is
//      rewritten. A slot with a clip uses it; a slot without one keeps its photo.
//
// To go back to the photo for a slot: delete public/cars/clips/<slot>.mp4 and run again.
// Needs ffmpeg (set FFMPEG=/path/to/ffmpeg if it is not on PATH).
import {spawnSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ff = process.env.FFMPEG || 'ffmpeg';
const IN = 'incoming';
const OUT = path.join('public', 'cars', 'clips');
const MANIFEST = path.join('src', 'lib', 'clips.generated.ts');

// slot -> orientation the film expects, and the width the clip is scaled to
const SLOTS = {
	k4: {o: 'landscape', w: 1920},
	a3: {o: 'landscape', w: 1920},
	rav4: {o: 'landscape', w: 1920},
	gle: {o: 'landscape', w: 1920},
	cayenne: {o: 'landscape', w: 1920},
	night: {o: 'landscape', w: 1920},
	macro: {o: 'portrait', w: 2160}, // the film pushes in 2.3x on it: keep the resolution
	pass: {o: 'portrait', w: 1080},
};

const run = (args) => {
	const r = spawnSync(ff, args, {encoding: 'utf8', maxBuffer: 1 << 28});
	if (r.error) {
		console.error(`cannot run ${ff}: ${r.error.message}\nInstall ffmpeg or set FFMPEG=/path/to/ffmpeg`);
		process.exit(1);
	}
	return r;
};

/** size (after rotation), duration, and whether the footage is HDR */
const probe = (file) => {
	const t = run(['-hide_banner', '-i', file]).stderr;
	const dur = t.match(/Duration: (\d+):(\d+):(\d+\.\d+)/);
	const size = t.match(/Stream #[^\n]*Video:[^\n]*?(\d{3,5})x(\d{3,5})/);
	const rot = t.match(/rotation of (-?\d+(?:\.\d+)?) degrees/);
	if (!dur || !size) return null;
	let w = +size[1];
	let h = +size[2];
	if (rot && Math.abs(Math.round(+rot[1])) % 180 === 90) [w, h] = [h, w];
	return {
		dur: +dur[1] * 3600 + +dur[2] * 60 + +dur[3],
		w,
		h,
		hdr: /arib-std-b67|smpte2084|bt2020/.test(t),
	};
};

fs.mkdirSync(OUT, {recursive: true});
fs.mkdirSync(IN, {recursive: true});

let converted = 0;
for (const f of fs.readdirSync(IN)) {
	const m = f.match(/^(.+)\.(mp4|mov|m4v|mkv)$/i);
	if (!m) continue;
	const slot = m[1].toLowerCase();
	const spec = SLOTS[slot];
	if (!spec) {
		console.warn(`skip  ${f}: unknown slot "${slot}" (expected: ${Object.keys(SLOTS).join(', ')})`);
		continue;
	}
	const src = path.join(IN, f);
	const info = probe(src);
	if (!info) {
		console.warn(`skip  ${f}: cannot read the video`);
		continue;
	}
	const isPortrait = info.h > info.w;
	if ((spec.o === 'portrait') !== isPortrait) {
		console.warn(`warn  ${f}: ${info.w}x${info.h} is ${isPortrait ? 'vertical' : 'horizontal'}, the film expects ${spec.o} for "${slot}"`);
	}
	const width = spec.o === 'landscape' && isPortrait ? 1080 : spec.w;
	const tone = info.hdr
		? 'zscale=t=linear:npl=100,format=gbrpf32le,zscale=p=bt709,tonemap=tonemap=hable:desat=0,zscale=t=bt709:m=bt709:r=tv,'
		: '';
	const dest = path.join(OUT, `${slot}.mp4`);
	const encode = (vf) =>
		run(['-hide_banner', '-loglevel', 'error', '-y', '-i', src, '-an', '-vf', vf, '-c:v', 'libx264', '-crf', '17', '-preset', 'medium', '-g', '15', '-movflags', '+faststart', dest]);
	let r = encode(`${tone}scale=${width}:-2:flags=lanczos,fps=30,format=yuv420p`);
	if (r.status !== 0 && info.hdr) {
		console.warn(`warn  ${f}: HDR tone-mapping failed (${r.stderr.trim().split('\n').pop()}); re-encoding without it`);
		r = encode(`scale=${width}:-2:flags=lanczos,fps=30,format=yuv420p`);
	}
	if (r.status !== 0) {
		console.error(`FAIL  ${f}: ${r.stderr.trim()}`);
		continue;
	}
	converted++;
	console.log(`ok    ${f} -> ${dest}  (${info.w}x${info.h}, ${info.dur.toFixed(1)} s${info.hdr ? ', HDR tone-mapped' : ''})`);
}

// rewrite the manifest from what is actually in public/cars/clips
const clips = {};
for (const f of fs.readdirSync(OUT).sort()) {
	const m = f.match(/^(.+)\.mp4$/);
	if (!m || !SLOTS[m[1]]) continue;
	const info = probe(path.join(OUT, f));
	if (info) clips[m[1]] = {dur: Math.round(info.dur * 100) / 100, w: info.w, h: info.h};
}
const body = Object.entries(clips)
	.map(([k, v]) => `\t${k}: {dur: ${v.dur}, w: ${v.w}, h: ${v.h}},`)
	.join('\n');
fs.writeFileSync(
	MANIFEST,
	`/**
 * GENERATED by scripts/prepare_clips.mjs — do not edit by hand.
 * One entry per clip found in public/cars/clips/<slot>.mp4.
 * While a slot has no clip, the film uses public/cars/<slot>.jpg instead.
 */
export const CLIPS: Record<string, {dur: number; w: number; h: number}> = {${body ? '\n' + body + '\n' : ''}};
`,
);
console.log(`\n${converted} clip(s) converted. Slots on video: ${Object.keys(clips).join(', ') || 'none (all photos)'}`);
const missing = Object.keys(SLOTS).filter((s) => !clips[s]);
if (missing.length) console.log(`Slots still on photo: ${missing.join(', ')}`);
